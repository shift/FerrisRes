#!/usr/bin/env python3
"""Generate the hardware evidence table from device and benchmark records.

The prose in `docs/hardware-matrix.md` says what a device is *expected* to do.
This script says what was *measured*, and refuses a record that does not name the
command, the date and the device.

Record format (one JSON file per record, any name):

  {
    "kind": "devices",
    "host": "i5-6500",
    "date": "2026-11-26",
    "command": "ferrisres devices --json",
    "adapters": [
      {"index": 0, "name": "Intel(R) HD Graphics 530 (SKL GT2)",
       "kind": "Integrated", "backend": "vulkan", "software": false,
       "max_buffer": 2147483647}
    ]
  }

  {
    "kind": "measurement",
    "host": "i5-6500",
    "date": "2026-11-26",
    "command": "ferrisres benchmark teacher --seq-len 128 --iterations 2",
    "device": "cpu",
    "metric": "teacher_prefill_tps",
    "value": 7.732,
    "unit": "tok/s",
    "seq_len": 128
  }

Usage:
  scripts/hardware_matrix.py --from records/            # print markdown
  scripts/hardware_matrix.py --from records/ --out table.md
  scripts/hardware_matrix.py --selftest
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import date
from pathlib import Path

ISO_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def _require(record: dict, key: str, errors: list[str]) -> None:
    value = record.get(key)
    if value is None or (isinstance(value, str) and not value.strip()):
        errors.append(f"missing {key!r}")


def validate(record: dict) -> list[str]:
    """Return the reasons this record cannot be evidence. Empty means valid."""
    errors: list[str] = []
    _require(record, "kind", errors)
    _require(record, "host", errors)
    _require(record, "date", errors)
    _require(record, "command", errors)

    day = record.get("date")
    if isinstance(day, str) and not ISO_DATE.match(day):
        errors.append("date must be YYYY-MM-DD")
    elif isinstance(day, str):
        try:
            date.fromisoformat(day)
        except ValueError:
            errors.append("date is not a real date")

    kind = record.get("kind")
    if kind == "devices":
        adapters = record.get("adapters")
        if not isinstance(adapters, list) or not adapters:
            errors.append("devices record needs a non-empty adapters list")
        else:
            for index, adapter in enumerate(adapters):
                for key in ("index", "name", "kind", "backend", "software"):
                    if key not in adapter:
                        errors.append(f"adapter[{index}] missing {key!r}")
                if not isinstance(adapter.get("software"), bool):
                    errors.append(f"adapter[{index}].software must be a bool")
    elif kind == "measurement":
        _require(record, "device", errors)
        _require(record, "metric", errors)
        if "value" not in record or not isinstance(record["value"], (int, float)):
            errors.append("measurement needs a numeric 'value'")
        _require(record, "unit", errors)
    elif kind not in (None, ""):
        errors.append(f"unknown kind {kind!r}")
    return errors


def render(records: list[dict], refused: list[tuple[str, list[str]]]) -> str:
    devices: list[dict] = []
    measurements: list[dict] = []
    for record in records:
        if record["kind"] == "devices":
            for adapter in record["adapters"]:
                devices.append({**adapter, "_record": record})
        else:
            measurements.append(record)

    lines: list[str] = []
    lines.append("<!-- generated by scripts/hardware_matrix.py; do not edit by hand -->")
    lines.append("")
    lines.append(
        f"Generated from {len(records)} record(s): "
        f"{len(devices)} adapter(s), {len(measurements)} measurement(s), "
        f"{len(refused)} refused."
    )
    lines.append("")

    lines.append("## Adapters observed")
    lines.append("")
    if devices:
        lines.append("| host | adapter | kind | backend | software | max buffer | command | date |")
        lines.append("|---|---|---|---|---:|---:|---|---|")
        for row in sorted(devices, key=lambda r: (r["_record"]["host"], r["index"])):
            record = row["_record"]
            lines.append(
                f"| {record['host']} | {row['name']} (#{row['index']}) | {row['kind']} | "
                f"{row['backend']} | {'yes' if row['software'] else 'no'} | "
                f"{row.get('max_buffer', '')} | `{record['command']}` | {record['date']} |"
            )
    else:
        lines.append("No adapter records.")
    lines.append("")

    lines.append("## Measurements")
    lines.append("")
    if measurements:
        lines.append("| host | device | metric | value | unit | seq | command | date |")
        lines.append("|---|---|---|---:|---|---:|---|---|")
        for row in sorted(
            measurements, key=lambda r: (r["host"], r["metric"], r.get("seq_len", 0))
        ):
            lines.append(
                f"| {row['host']} | {row['device']} | {row['metric']} | {row['value']} | "
                f"{row['unit']} | {row.get('seq_len', '')} | `{row['command']}` | {row['date']} |"
            )
    else:
        lines.append("No measurement records.")
    lines.append("")

    if refused:
        lines.append("## Refused records")
        lines.append("")
        for name, reasons in refused:
            lines.append(f"- `{name}`: {'; '.join(reasons)}")
        lines.append("")
    lines.append(
        "A row is evidence only if it names the command, the date and the device. "
        "A calculated number is not a measurement and belongs in the prose, not here."
    )
    lines.append("")
    return "\n".join(lines)


def load(directory: Path) -> tuple[list[dict], list[tuple[str, list[str]]]]:
    records: list[dict] = []
    refused: list[tuple[str, list[str]]] = []
    for path in sorted(directory.glob("*.json")):
        try:
            record = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError) as error:
            refused.append((path.name, [f"unreadable: {error}"]))
            continue
        if not isinstance(record, dict):
            refused.append((path.name, ["top level must be an object"]))
            continue
        reasons = validate(record)
        if reasons:
            refused.append((path.name, reasons))
        else:
            records.append(record)
    return records, refused


def selftest() -> int:
    good_devices = {
        "kind": "devices",
        "host": "i5-6500",
        "date": "2026-11-26",
        "command": "ferrisres devices --json",
        "adapters": [
            {
                "index": 0,
                "name": "Intel(R) HD Graphics 530 (SKL GT2)",
                "kind": "Integrated",
                "backend": "vulkan",
                "software": False,
                "max_buffer": 2147483647,
            }
        ],
    }
    good_measurement = {
        "kind": "measurement",
        "host": "i5-6500",
        "date": "2026-11-26",
        "command": "ferrisres benchmark teacher --seq-len 128",
        "device": "cpu",
        "metric": "teacher_prefill_tps",
        "value": 7.732,
        "unit": "tok/s",
        "seq_len": 128,
    }
    bad = dict(good_measurement)
    bad.pop("command")
    bad["date"] = "26/11/2026"

    failures: list[str] = []
    if validate(good_devices):
        failures.append("valid devices record was refused")
    if validate(good_measurement):
        failures.append("valid measurement was refused")
    reasons = validate(bad)
    if not reasons:
        failures.append("invalid record was accepted")
    if not any("command" in reason for reason in reasons):
        failures.append("missing command was not named")
    if not any("date" in reason for reason in reasons):
        failures.append("bad date was not named")

    table = render([good_devices, good_measurement], [("bad.json", reasons)])
    for expected in (
        "Intel(R) HD Graphics 530",
        "teacher_prefill_tps",
        "7.732",
        "Refused records",
        "bad.json",
    ):
        if expected not in table:
            failures.append(f"table missing {expected!r}")

    if failures:
        for failure in failures:
            print(f"FAIL: {failure}", file=sys.stderr)
        return 1
    print("selftest: ok (2 valid, 1 refused, table fields present)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from", dest="directory", type=Path, help="directory of *.json records")
    parser.add_argument("--out", type=Path, help="write markdown here instead of stdout")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()

    if args.selftest:
        return selftest()
    if not args.directory:
        parser.error("--from is required unless --selftest is given")
    if not args.directory.is_dir():
        parser.error(f"not a directory: {args.directory}")

    records, refused = load(args.directory)
    table = render(records, refused)
    if args.out:
        args.out.write_text(table)
        print(f"wrote {args.out} ({len(records)} records, {len(refused)} refused)")
    else:
        print(table)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
